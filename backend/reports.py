"""Export generators: PDF (reportlab), Word (python-docx), Excel (openpyxl), QR (qrcode)."""
import io

import qrcode
from docx import Document
from docx.shared import RGBColor
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

BRAND = colors.HexColor("#0A3B2A")
_styles = getSampleStyleSheet()
H1 = ParagraphStyle("h1", parent=_styles["Title"], textColor=BRAND, alignment=0, fontSize=22, spaceAfter=6)
H2 = ParagraphStyle("h2", parent=_styles["Heading2"], textColor=BRAND, spaceBefore=12)
EYEBROW = ParagraphStyle("eb", parent=_styles["Normal"], fontSize=8, textColor=colors.HexColor("#64748b"))
BODY = ParagraphStyle("body", parent=_styles["BodyText"], fontSize=10, leading=14)


def _esc(v) -> str:
    return str(v if v not in (None, "") else "—").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\n", "<br/>")


def _table(rows, header=True, widths=None):
    t = Table([[Paragraph(_esc(c), BODY) for c in r] for r in rows], colWidths=widths, repeatRows=1 if header else 0)
    style = [("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#E2E8F0")), ("VALIGN", (0, 0), (-1, -1), "TOP")]
    if header:
        style += [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F0F4F2"))]
    t.setStyle(TableStyle(style))
    return t


def build_pdf(title: str, eyebrow: str, blocks: list) -> bytes:
    """blocks: list of ("h", text) | ("p", text) | ("kv", [(k, v)...]) | ("table", rows)."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=18 * mm, bottomMargin=18 * mm, title=title)
    story = [Paragraph(_esc(eyebrow).upper(), EYEBROW), Paragraph(_esc(title), H1), Spacer(1, 6)]
    for kind, content in blocks:
        if kind == "h":
            story.append(Paragraph(_esc(content), H2))
        elif kind == "p":
            story.append(Paragraph(_esc(content), BODY))
            story.append(Spacer(1, 4))
        elif kind == "kv":
            story.append(_table([[k, v] for k, v in content], header=False, widths=[60 * mm, None]))
        elif kind == "table" and content:
            story.append(_table(content))
    story.append(Spacer(1, 16))
    story.append(Paragraph("Generated by Sustainability360", EYEBROW))
    doc.build(story)
    return buf.getvalue()


def build_docx(title: str, eyebrow: str, blocks: list) -> bytes:
    d = Document()
    d.add_paragraph(eyebrow.upper())
    h = d.add_heading(title, 0)
    for r in h.runs:
        r.font.color.rgb = RGBColor(0x0A, 0x3B, 0x2A)
    for kind, content in blocks:
        if kind == "h":
            d.add_heading(content, 2)
        elif kind == "p":
            d.add_paragraph(str(content or "—"))
        elif kind in ("kv", "table") and content:
            rows = [[k, v] for k, v in content] if kind == "kv" else content
            t = d.add_table(rows=len(rows), cols=len(rows[0]))
            t.style = "Light Grid Accent 1"
            for i, row in enumerate(rows):
                for j, c in enumerate(row):
                    t.cell(i, j).text = "—" if c in (None, "") else str(c)
    buf = io.BytesIO()
    d.save(buf)
    return buf.getvalue()


def build_xlsx(sheets: dict) -> bytes:
    """sheets: {name: rows} — first row is the header."""
    wb = Workbook()
    wb.remove(wb.active)
    for name, rows in sheets.items():
        ws = wb.create_sheet(name[:31])
        for r in rows:
            ws.append(["" if c is None else c for c in r])
        if rows:
            for c in ws[1]:
                c.font = Font(bold=True, color="FFFFFF")
                c.fill = PatternFill("solid", fgColor="0A3B2A")
        for col in ws.columns:
            ws.column_dimensions[col[0].column_letter].width = min(60, max(12, *(len(str(c.value or "")) + 2 for c in col)))
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def build_qr(data: str) -> bytes:
    img = qrcode.make(data, box_size=10, border=2)
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()
